import { access, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
const root = new URL('../', import.meta.url);
for (const file of ['index.html', 'style.css', 'app.js', 'assets/campaign-frame.png', 'assets/alliance-circle.png', 'assets/alliance-logo.png', 'assets/alliance-wide.png', 'assets/alliance-wide-preview.webp', 'assets/alliance-logo-preview.webp', 'assets/alliance-circle-preview.webp', 'assets/alliance-symbol.webp', 'assets/campaign-frame-lossless.webp']) await access(new URL(file, root));
execFileSync(process.execPath, ['--check', fileURLToPath(new URL('app.js', root))]);
execFileSync(process.execPath, ['--check', fileURLToPath(new URL('server.mjs', root))]);
const html = await readFile(new URL('index.html', root), 'utf8');
if (!html.includes('app.js') || !html.includes('style.css')) throw new Error('Missing page resources');
console.log('Static app and all image assets are ready. No compilation required.');
